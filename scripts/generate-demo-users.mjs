// One-off script: hashes demo-account passwords and writes a D1 migration.
// Must stay in sync with the PBKDF2-SHA256 scheme implemented in
// src/lib/password.ts (same iteration count and `pbkdf2$iter$salt$hash` format),
// so the Worker can verify passwords hashed here.
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ITERATIONS = 100_000

function toHex(bytes) {
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('')
}

async function hashPassword(password) {
  const salt = crypto.getRandomValues(new Uint8Array(16))
  const keyMaterial = await crypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(password),
    'PBKDF2',
    false,
    ['deriveBits']
  )
  const bits = await crypto.subtle.deriveBits(
    { name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    keyMaterial,
    256
  )
  return `pbkdf2$${ITERATIONS}$${toHex(salt)}$${toHex(new Uint8Array(bits))}`
}

function sqlString(value) {
  return `'${value.replace(/'/g, "''")}'`
}

