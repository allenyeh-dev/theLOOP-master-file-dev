const lines = [
  '-- Generated by scripts/generate-demo-users.mjs — do not edit hashes by hand.',
  '-- Demo credentials (change or remove before production use):',
  ...demoUsers.map((u) => `--   ${u.email} / ${u.password}  (${u.role})`),
  '',
]

for (const u of demoUsers) {
  const hash = await hashPassword(u.password)
  lines.push(
    `INSERT INTO users (name, email, password_hash, title, role_id, is_active)\n` +
      `VALUES (${sqlString(u.name)}, ${sqlString(u.email)}, ${sqlString(hash)}, ${sqlString(u.title)}, (SELECT id FROM roles WHERE key = ${sqlString(u.role)}), 1);`
  )
}

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const outPath = path.join(__dirname, '..', 'migrations', '0003_seed_demo_users.sql')
await writeFile(outPath, lines.join('\n\n') + '\n')

